use std::fmt::Write as _;
use std::fs;

use crate::atomicfile;
use crate::config::{Config, Site, TLS_AUTO, TLS_INTERNAL};
use crate::pages::{self, esc};

const STRIPPED: &[&str] = &[
    "X-Ship-Rs-Email",
    "X-Ship-Rs-Provider",
    "Remote-User",
    "Remote-Email",
    "Remote-Name",
    "Remote-Groups",
    "X-Remote-User",
    "X-Forwarded-User",
    "X-Forwarded-Email",
];

pub fn caddyfile(cfg: &Config) -> Result<String, String> {
    if cfg.base_domain.is_empty() || cfg.auth_upstream.is_empty() || cfg.hub.deploy.as_os_str().is_empty() {
        return Err("config is incomplete".into());
    }
    let mut b = String::new();
    let _ = writeln!(b, "# Generated by ship-rs from {}. Do not edit.", cfg.path.display());
    b.push_str("# Edit sites.toml, then run ship-rs generate or ship-rs deploy.\n");
    if let Some(global) = global_block(cfg) {
        b.push('\n');
        b.push_str(&global);
    }
    b.push('\n');
    write_auth(&mut b, cfg);
    write_apex(&mut b, cfg);
    write_www(&mut b, cfg);
    for site in &cfg.sites {
        if site.enabled {
            write_site(&mut b, cfg, site);
        }
    }
    if !cfg.preview_addr.is_empty() {
        write_preview(&mut b, cfg);
    }
    Ok(b)
}

fn global_block(cfg: &Config) -> Option<String> {
    let mut lines = Vec::new();
    if cfg.caddy_admin == "off" {
        lines.push("\tadmin off".to_string());
    } else if !cfg.caddy_admin.is_empty() {
        lines.push(format!("\tadmin {}", cfg.caddy_admin));
    }
    if cfg.tls == TLS_AUTO && !cfg.acme_email.is_empty() {
        lines.push(format!("\temail {}", cfg.acme_email));
    }
    if cfg.tls == TLS_INTERNAL {
        lines.push("\tlocal_certs".to_string());
    }
    if cfg.http_port != 80 || cfg.https_port != 443 {
        lines.push(format!("\thttp_port {}", cfg.http_port));
        lines.push(format!("\thttps_port {}", cfg.https_port));
    }
    if lines.is_empty() {
        None
    } else {
        Some(format!("{{\n{}\n}}\n", lines.join("\n")))
    }
}

fn write_auth(b: &mut String, cfg: &Config) {
    let _ = writeln!(b, "auth.{} {{", cfg.base_domain);
    write_response_strip(b, "\t");
    let _ = writeln!(b, "\treverse_proxy {} {{", cfg.auth_upstream);
    write_header_up_strip(b, "\t\t");
    b.push_str("\t}\n}\n\n");
}

fn write_apex(b: &mut String, cfg: &Config) {
    let _ = writeln!(b, "{} {{", cfg.base_domain);
    let _ = writeln!(b, "\troot * {}", cfg.hub.deploy.display());
    b.push_str("\tencode gzip zstd\n");
    write_response_strip(b, "\t");
    write_request_strip(b, "\t");
    b.push_str("\tfile_server\n}\n\n");
}

fn write_www(b: &mut String, cfg: &Config) {
    let _ = writeln!(b, "www.{} {{", cfg.base_domain);
    let _ = writeln!(b, "\tredir https://{}{{uri}} permanent\n}}\n", cfg.display_host(&cfg.base_domain));
}

fn write_site(b: &mut String, cfg: &Config, site: &Site) {
    let _ = writeln!(b, "{} {{", site.fqdn);
    let _ = writeln!(b, "\troot * {}", site.deploy.display());
    b.push_str("\tencode gzip zstd\n");
    write_response_strip(b, "\t");
    if site.public {
        write_request_strip(b, "\t");
        if site.spa {
            b.push_str("\troute {\n");
            b.push_str("\t\ttry_files {path} /index.html\n");
            b.push_str("\t\tfile_server\n");
            b.push_str("\t}\n");
        } else {
            b.push_str("\tfile_server\n");
        }
        if cfg.tls == TLS_INTERNAL {
            b.push_str("\ttls internal\n");
        }
        b.push_str("}\n\n");
        return;
    }
    b.push_str("\troute {\n");
    write_request_strip(b, "\t\t");
    let _ = writeln!(b, "\t\tforward_auth {} {{", cfg.auth_upstream);
    b.push_str("\t\t\turi /check\n");
    b.push_str("\t\t\tcopy_headers X-Ship-Rs-Email\n");
    write_header_up_strip(b, "\t\t\t");
    b.push_str("\t\t\theader_up X-Forwarded-Uri {http.request.orig_uri}\n");
    b.push_str("\t\t\theader_up X-Forwarded-Method {http.request.method}\n");
    b.push_str("\t\t}\n");
    if site.spa {
        b.push_str("\t\ttry_files {path} /index.html\n");
    }
    b.push_str("\t\tfile_server\n");
    b.push_str("\t}\n");
    if cfg.tls == TLS_INTERNAL {
        b.push_str("\ttls internal\n");
    }
    b.push_str("}\n\n");
}

fn write_preview(b: &mut String, cfg: &Config) {
    let _ = writeln!(b, "http://{} {{", cfg.preview_addr);
    let _ = writeln!(b, "\troot * {}", cfg.hub.deploy.display());
    b.push_str("\tfile_server\n}\n\n");
}

fn write_response_strip(b: &mut String, indent: &str) {
    let _ = writeln!(b, "{indent}header {{");
    for h in STRIPPED {
        let _ = writeln!(b, "{indent}\t-{h}");
    }
    let _ = writeln!(b, "{indent}}}");
}

fn write_request_strip(b: &mut String, indent: &str) {
    for h in STRIPPED {
        let _ = writeln!(b, "{indent}request_header -{h}");
    }
}

fn write_header_up_strip(b: &mut String, indent: &str) {
    for h in STRIPPED {
        let _ = writeln!(b, "{indent}header_up -{h}");
    }
}

pub fn hub_html(cfg: &Config) -> String {
    let mut sites = String::new();
    let listed = cfg.listed();
    if listed.is_empty() {
        sites.push_str("<p class=\"card\">No sites are listed.</p>\n");
    } else {
        sites.push_str("<ul class=\"sites\">\n");
        for site in &listed {
            let (class, badge) = if site.public { ("public", "Public") } else { ("protected", "Sign-in required") };
            let _ = write!(
                sites,
                "<li>\n<a href=\"{}\">\n<span class=\"title\">{}</span>\n<span class=\"host\">{}</span>\n</a>\n<span class=\"badge {class}\">{badge}</span>\n</li>\n",
                esc(&cfg.site_origin(site)),
                esc(&site.title),
                esc(&cfg.display_host(&site.fqdn))
            );
        }
        sites.push_str("</ul>\n");
    }
    format!(
        "<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n<title>{}</title>\n<style>{}</style>\n</head>\n<body>\n<main>\n<p class=\"mark\">ship-rs</p>\n<h1>{}</h1>\n<p class=\"lede\">Sites on {}. A lock means the site asks you to sign in.</p>\n{sites}</main>\n</body>\n</html>\n",
        esc(&cfg.hub.title),
        pages::css(),
        esc(&cfg.hub.title),
        esc(&cfg.base_domain)
    )
}

pub fn write(cfg: &Config) -> Result<(), String> {
    if cfg.caddyfile.as_os_str().is_empty() {
        return Err("caddyfile path is empty".into());
    }
    let body = caddyfile(cfg)?;
    let page = hub_html(cfg);
    fs::create_dir_all(&cfg.hub.deploy).map_err(|e| e.to_string())?;
    atomicfile::write(&cfg.hub.deploy.join("index.html"), page.as_bytes(), 0o644).map_err(|e| e.to_string())?;
    if let Some(parent) = cfg.caddyfile.parent() {
        fs::create_dir_all(parent).map_err(|e| e.to_string())?;
    }
    atomicfile::write(&cfg.caddyfile, body.as_bytes(), 0o644).map_err(|e| e.to_string())?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config;
    use std::fs;

    #[test]
    fn caddyfile_shapes() {
        let cfg = load(
            r#"
base_domain = "example.com"
acme_email = "admin@example.com"
tls = "internal"
http_port = 18080
https_port = 18443
auth_upstream = "127.0.0.1:8091"
caddyfile = "Caddyfile"
caddy_admin = "off"
admins = ["owner@example.com"]

[hub]
title = "Example sites"
deploy = "hub"

[[sites]]
slug = "hello"
title = "Public hello"
deploy = "hello"
subdomain = "hello"
public = true

[[sites]]
slug = "notes"
title = "Protected hello"
deploy = "notes"
subdomain = "notes"
public = false
allow = ["guest@example.com"]

[[sites]]
slug = "spa"
title = "SPA demo"
deploy = "spa"
subdomain = "spa"
public = true
spa = true

[[sites]]
slug = "old"
title = "Retired"
deploy = "old"
subdomain = "old"
public = false
enabled = false
"#,
        );
        let file = caddyfile(&cfg).unwrap();
        assert_eq!(file.matches("forward_auth ").count(), 1, "{file}");
        assert!(!file.contains("old.example.com"), "{file}");
        assert!(file.contains("header_up -X-Ship-Rs-Email"));
        assert!(file.contains("copy_headers X-Ship-Rs-Email"));
        assert!(file.contains("reverse_proxy 127.0.0.1:8091"));
        assert!(file.contains("try_files {path} /index.html"));
        assert_eq!(file.matches("try_files").count(), 1, "{file}");
        assert!(!file.contains("xcaddy"));
        let public = between(&file, "hello.example.com {", "notes.example.com {");
        assert!(!public.contains("forward_auth"), "{public}");
        let protected = between(&file, "notes.example.com {", "spa.example.com {");
        assert!(protected.contains("forward_auth 127.0.0.1:8091"), "{protected}");
        assert!(!protected.contains("try_files"), "{protected}");
        assert!(file.contains("local_certs"));
        assert!(file.contains("https_port 18443"));
        assert!(file.contains("admin off"));
        let hub = hub_html(&cfg);
        assert!(hub.contains("Public hello"));
        assert!(hub.contains("Protected hello"));
        assert!(!hub.contains("Retired"));
        assert!(hub.contains("Sign-in required"));
        assert!(hub.contains("https://notes.example.com:18443/"));
    }

    fn between<'a>(file: &'a str, start: &str, end: &str) -> &'a str {
        let Some(i) = file.find(start) else { return "" };
        let rest = &file[i..];
        match rest.find(end) {
            Some(j) => &rest[..j],
            None => rest,
        }
    }

    fn load(body: &str) -> Config {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("sites.toml");
        fs::write(&path, body).unwrap();
        let cfg = config::load(&path).unwrap();
        std::mem::forget(dir);
        cfg
    }
}
