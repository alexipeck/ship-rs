#!/bin/sh
set -eu

bundle=${1:-}
if [ -z "$bundle" ] || [ ! -d "$bundle" ]; then
  echo "usage: remote-bootstrap.sh BUNDLE_DIR" >&2
  exit 2
fi

if [ "$(id -u)" -ne 0 ]; then
  echo "remote-bootstrap.sh must run as root" >&2
  exit 1
fi

if [ "$(uname -m)" != "x86_64" ]; then
  echo "this binary is x86_64-unknown-linux-gnu; this machine is $(uname -m)" >&2
  exit 1
fi

if [ ! -r /etc/os-release ]; then
  echo "missing /etc/os-release" >&2
  exit 1
fi

. /etc/os-release
if [ "${ID:-}" != "arch" ]; then
  echo "this installer expects Arch Linux (ID=arch); found ${ID:-unknown}" >&2
  exit 1
fi

if ! command -v pacman >/dev/null 2>&1; then
  echo "pacman is not installed" >&2
  exit 1
fi

glibc=$(ldd --version | awk 'NR==1 { print $NF }')
oldest=$(printf '%s\n%s\n' "2.39" "$glibc" | sort -V | head -n 1)
if [ "$oldest" != "2.39" ]; then
  echo "sitegate needs glibc 2.39 or newer; this machine has $glibc" >&2
  exit 1
fi

expected=$(tr -d '[:space:]' < "$bundle/prebuilt/sitegate.sha256")
actual=$(sha256sum "$bundle/prebuilt/sitegate" | awk '{ print $1 }')
if [ "$expected" != "$actual" ]; then
  echo "binary checksum mismatch" >&2
  exit 1
fi

pacman -S --needed --noconfirm caddy rsync openssl curl

install -m 0755 "$bundle/prebuilt/sitegate" /usr/local/bin/sitegate

if ! id sitegate >/dev/null 2>&1; then
  nologin=$(command -v nologin || true)
  if [ -z "$nologin" ]; then
    nologin=/usr/bin/nologin
  fi
  useradd --system --home-dir /var/lib/sitegate --create-home --shell "$nologin" sitegate
fi

install -d -m 0755 /etc/sitegate /srv/sitegate/hub /srv/sitegate/sites /srv/sitegate/src /var/lib/sitegate

install_example() {
  name=$1
  src=$2
  for dest in "/srv/sitegate/src/$name" "/srv/sitegate/sites/$name"; do
    if [ -d "$dest" ] && [ -n "$(find "$dest" -mindepth 1 -print -quit)" ]; then
      echo "keeping existing $dest"
      continue
    fi
    install -d -m 0755 "$dest"
    cp -a "$src"/. "$dest"/
    find "$dest" -type d -exec chmod 0755 {} +
    find "$dest" -type f -exec chmod 0644 {} +
    echo "installed example site $dest"
  done
}

install_example hello "$bundle/examples/public-hello"
install_example notes "$bundle/examples/protected-hello"
install_example spa "$bundle/examples/spa-demo"

config_installed=0
if [ ! -f /etc/sitegate/sites.toml ]; then
  install -m 0644 "$bundle/deploy/sites.arch.toml" /etc/sitegate/sites.toml
  config_installed=1
  echo "wrote /etc/sitegate/sites.toml"
else
  echo "keeping existing /etc/sitegate/sites.toml"
fi

if [ ! -f /etc/sitegate/sitegate.env ]; then
  key=$(openssl rand -base64 32 | tr -d '\n')
  umask 077
  awk -v key="$key" '
    BEGIN { FS = OFS = "=" }
    $1 == "SITEGATE_COOKIE_KEY" && $2 == "" { $2 = key }
    { print }
  ' "$bundle/deploy/sitegate.env.example" > /etc/sitegate/sitegate.env
  chmod 0600 /etc/sitegate/sitegate.env
  chown root:root /etc/sitegate/sitegate.env
  echo "wrote /etc/sitegate/sitegate.env with a new cookie key"
else
  echo "keeping existing /etc/sitegate/sitegate.env"
fi

install -m 0644 "$bundle/deploy/sitegate.service" /etc/systemd/system/sitegate.service
systemctl daemon-reload
systemctl enable sitegate
if ! systemctl restart sitegate; then
  systemctl --no-pager --full status sitegate || true
  journalctl -u sitegate -n 40 --no-pager || true
  exit 1
fi

if [ "$config_installed" -eq 1 ]; then
  if [ -f /etc/caddy/Caddyfile ] && ! grep -q "Generated by sitegate" /etc/caddy/Caddyfile; then
    cp -a /etc/caddy/Caddyfile /etc/caddy/Caddyfile.before-sitegate
    echo "saved the previous Caddyfile as /etc/caddy/Caddyfile.before-sitegate"
  fi
  /usr/local/bin/sitegate generate --config /etc/sitegate/sites.toml
fi

/usr/local/bin/sitegate validate --config /etc/sitegate/sites.toml

ok=0
i=0
while [ "$i" -lt 30 ]; do
  if curl -fsS http://127.0.0.1:8091/healthz >/dev/null; then
    ok=1
    break
  fi
  i=$((i + 1))
  sleep 0.2
done

if [ "$ok" -ne 1 ]; then
  systemctl --no-pager --full status sitegate || true
  journalctl -u sitegate -n 40 --no-pager || true
  echo "sitegate did not answer on 127.0.0.1:8091" >&2
  exit 1
fi

echo
echo "sitegate $(/usr/local/bin/sitegate version) is running on 127.0.0.1:8091"
echo "Edit /etc/sitegate/sites.toml (base_domain, acme_email, admins, allowlists)."
echo "Edit /etc/sitegate/sitegate.env (Google and GitHub client id and secret), then: systemctl restart sitegate"
echo "When DNS points at this machine and you want Caddy to serve: sitegate deploy --config /etc/sitegate/sites.toml --reload && systemctl enable --now caddy"
echo "This installer did not change the firewall."
